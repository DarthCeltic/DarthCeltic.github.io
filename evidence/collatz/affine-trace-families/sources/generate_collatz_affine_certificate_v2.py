#!/usr/bin/env python3
"""Generate one Lean-checkable universal affine descent certificate from M29 or M31."""

from __future__ import annotations

import argparse
import gzip
import hashlib
import json
from pathlib import Path
from typing import Any


REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_SCAN = REPO_ROOT / "research" / "collatz" / "m31-exploratory" / "scan" / "m31-residual-affine-screen.json.gz"
SCAN_DEPTHS = {
    "collatz-m29-residual-affine-screen-exploratory-v1": 29,
    "collatz-m31-residual-affine-screen-exploratory-v1": 31,
}


class CertificateError(ValueError):
    """Raised when the selected arithmetic row is not a valid affine trace."""


def _trace_states(row: dict[str, Any]) -> list[tuple[int, int]]:
    modulus, residue = row.get("modulus"), row.get("r")
    steps, parity_word = row.get("steps"), row.get("parity_word")
    if type(modulus) is not int or modulus <= 0 or type(residue) is not int or residue < 0:
        raise CertificateError("modulus and residue must be nonnegative integers, with positive modulus")
    if type(steps) is not int or steps <= 0 or not isinstance(parity_word, str) or len(parity_word) != steps:
        raise CertificateError("step count and parity word length differ")

    slope, intercept = modulus, residue
    states = [(slope, intercept)]
    for index, parity in enumerate(parity_word):
        if slope % 2:
            raise CertificateError(f"affine slope is odd before step {index + 1}")
        if parity == "O":
            if intercept % 2 != 1:
                raise CertificateError(f"odd parity is invalid at step {index + 1}")
            slope, intercept = 3 * slope, 3 * intercept + 1
        elif parity == "E":
            if intercept % 2 != 0:
                raise CertificateError(f"even parity is invalid at step {index + 1}")
            slope, intercept = slope // 2, intercept // 2
        else:
            raise CertificateError(f"unsupported parity symbol at step {index + 1}")
        states.append((slope, intercept))

    if (slope, intercept) != (row.get("endpoint_a"), row.get("endpoint_b")):
        raise CertificateError("recorded affine endpoint differs from the parity recurrence")
    if row.get("strict_gap_coeff") != modulus - slope or row.get("strict_gap_const") != residue - intercept:
        raise CertificateError("recorded strict gap differs from the affine endpoints")
    if slope > modulus or intercept >= residue:
        raise CertificateError("affine endpoint does not establish strict descent")
    return states


def render_certificate(row: dict[str, Any], scan_sha256: str, *, depth: int | None = None) -> bytes:
    """Render a deterministic Lean module containing the generic theorem and one row."""
    if not isinstance(scan_sha256, str) or len(scan_sha256) != 64:
        raise CertificateError("scan digest must be a SHA-256 hex string")
    try:
        bytes.fromhex(scan_sha256)
    except ValueError as exc:
        raise CertificateError("scan digest is not hexadecimal") from exc
    states = _trace_states(row)
    modulus, residue = row["modulus"], row["r"]
    steps, endpoint_a, endpoint_b = row["steps"], row["endpoint_a"], row["endpoint_b"]
    depth = depth if depth is not None else row.get("m", modulus.bit_length() - 1)
    if type(depth) is not int or depth < 1 or modulus != 1 << depth:
        raise CertificateError("certificate depth does not match its power-of-two modulus")
    if row.get("m", depth) != depth:
        raise CertificateError("row depth differs from its certificate depth")
    namespace_name = f"m{depth}Residue{residue}"
    theorem_name = "universalDescent"
    generator_path = (
        "scripts/generate_collatz_affine_certificate_v2.py"
        if depth == 29
        else "scripts/generate_collatz_affine_certificate.py"
    )

    lines = [
        f"-- Generated by {generator_path}.",
        f"-- Arithmetic-only parent scan SHA-256: {scan_sha256.lower()}.",
        "import Mathlib.Data.Nat.Prime.Basic",
        "import CollatzAffineTrace",
        "",
        f"namespace MathCase.CollatzAffineTrace.{namespace_name}",
        "",
        "open MathCase.CollatzAffineTrace",
        "",
    ]

    for index, ((slope, intercept), (next_slope, next_intercept)) in enumerate(zip(states, states[1:])):
        parity = row["parity_word"][index]
        condition = "= 0" if parity == "E" else "≠ 0"
        lines += [
            f"theorem step{index} : ∀ k : Nat, collatzStep ({slope} * k + {intercept}) = {next_slope} * k + {next_intercept} := by",
            "  intro k",
            "  unfold collatzStep",
            f"  simp [show ({slope} * k + {intercept}) % 2 {condition} by omega]",
            "  omega",
            "",
        ]

    lines += [
        f"theorem trace : AffineTrace ({modulus}, {residue}) {steps} ({endpoint_a}, {endpoint_b}) :=",
    ]
    for index in range(steps):
        slope, intercept = states[index]
        next_slope, next_intercept = states[index + 1]
        remaining = steps - index - 1
        lines.append(
            f"  {'  ' * index}AffineTrace.step "
            f"(start := ({slope}, {intercept})) "
            f"(middle := ({next_slope}, {next_intercept})) "
            f"(finish := ({endpoint_a}, {endpoint_b})) "
            f"(steps := {remaining}) step{index} ("
        )
    lines += [
        f"  {'  ' * steps}AffineTrace.done (state := ({endpoint_a}, {endpoint_b}))" + ")" * steps,
        "",
        f"theorem {theorem_name} : ∀ k : Nat,",
        f"    iterate ({modulus} * k + {residue}) {steps} = {endpoint_a} * k + {endpoint_b} ∧",
        f"      {endpoint_a} * k + {endpoint_b} < {modulus} * k + {residue} := by",
        "  refine affineTraceDescent trace (by omega) (by omega)",
        "",
        f"end MathCase.CollatzAffineTrace.{namespace_name}",
        "",
        f"#print axioms MathCase.CollatzAffineTrace.{namespace_name}.{theorem_name}",
        "",
    ]
    return "\n".join(lines).encode("utf-8")


def generate(scan_path: Path, residue: int) -> tuple[bytes, dict[str, Any]]:
    scan_bytes = scan_path.read_bytes()
    try:
        scan = json.loads(gzip.decompress(scan_bytes))
    except (OSError, EOFError, gzip.BadGzipFile, json.JSONDecodeError) as exc:
        raise CertificateError(f"cannot read compressed arithmetic scan: {exc}") from exc
    schema = scan.get("schema")
    depth = SCAN_DEPTHS.get(schema)
    if depth is None:
        raise CertificateError("unsupported arithmetic scan schema")
    if scan.get("classification") != "EXPLORATORY_ARITHMETIC_ONLY":
        raise CertificateError("parent scan is not explicitly arithmetic-only")
    matches = [row for row in scan.get("families", []) if row.get("r") == residue]
    if len(matches) != 1:
        raise CertificateError("selected residue must have exactly one scan row")
    row = matches[0]
    if row.get("m") != depth or row.get("modulus") != 1 << depth:
        raise CertificateError("selected row depth or modulus differs from its scan schema")
    digest = hashlib.sha256(scan_bytes).hexdigest()
    source = render_certificate(row, digest, depth=depth)
    return source, {
        "classification": "PENDING_LEAN_CHECK",
        "parent_classification": "EXPLORATORY_ARITHMETIC_ONLY",
        "parent_scan_sha256": digest,
        "depth": depth,
        "residue": residue,
        "steps": row["steps"],
        "lean_source_sha256": hashlib.sha256(source).hexdigest(),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--scan", type=Path, default=DEFAULT_SCAN)
    parser.add_argument("--residue", type=int, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    if args.output.exists():
        parser.error(f"refusing to overwrite existing output: {args.output}")
    try:
        source, receipt = generate(args.scan, args.residue)
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_bytes(source)
    except (OSError, CertificateError) as exc:
        parser.error(str(exc))
    print(json.dumps({"output": args.output.as_posix(), "source_sha256": receipt["lean_source_sha256"], **receipt}, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
